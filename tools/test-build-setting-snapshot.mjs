import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import vm from 'node:vm';

const root = resolve(import.meta.dirname, '..');
const local = new Map();
const files = new Map();
let restored = null;
let build = { character:{ level:325, attributes:{ STR:510, INT:1, VIT:1, AGI:1, DEX:1, CRT:0 } }, equipment:{ mainWeapon:{}, subWeapon:{}, armor:{}, additional:{}, special:{} }, skillLevels:{ Blade:{ 0:10 } }, activeBuffs:{}, externalOptions:[], combo:[] };
const scenario = { target:{ bossLevel:300, bossDef:100, bossMdef:100, bossPhysResist:0, bossMagResist:0, bossCritResist:0 }, conditions:{}, optimizationPreferences:{ rangeOverride:'LONG', requirements:{ maxHp:null, maxMp:2500 }, bannedCrystas:['저장 제외 크리스타'] } };
const document = { readyState:'loading', addEventListener() {}, createElement() { return { click() {}, remove() {}, href:'', download:'' }; }, body:{ appendChild() {} } };
const window = {
  localStorage:{ getItem:key => local.get(key) ?? null, setItem:(key, value) => local.set(key, String(value)) }, setTimeout:callback => callback(),
  ToramBuildDraftStore:{ read:() => ({ build, scenario }) }, ToramBuildStateUi:{ restoreSession:value => { restored = value; build = value.build; } },
  ToramSettingsFileRepositoryAdapter:{ directory:async () => 'C:\\Settings', list:async () => [...files.keys()].map(name => ({ name, lastModified:1 })), save:async (name, content) => { if (files.has(name + '.json')) throw new Error('duplicate'); files.set(name + '.json', content); }, load:async name => files.get(name), overwrite:async (name, content) => files.set(name, content), delete:async name => files.delete(name) }
};
window.window = window;
const context = { window, document, console, JSON, Date, Blob, URL:{ createObjectURL:() => '', revokeObjectURL() {} } };
vm.createContext(context);
vm.runInContext(await readFile(resolve(root, 'assets/js/settings-repository.js'), 'utf8'), context, { filename:'settings-repository.js' });
const repository = window.ToramSettingsRepository;
build.myRoomFood = [{id:'STR',level:10},null,{id:'ELEM_P',level:6},{id:'PHYS_RES',level:10},null];
const expectedFood = JSON.parse(JSON.stringify(build.myRoomFood));
build.guildFoodBuff = false;

assert.equal(repository.format, 'toram-auto-build-document');
assert.equal(repository.schemaVersion, 2);
const saved = await repository.save('  R6:/빌드... ');
assert.equal(saved.name, 'R6--빌드');
assert.equal(files.size, 1);
const stored = repository.parseSavedBuild(files.get('R6--빌드.json'));
assert.equal(stored.documentType, 'saved-build');
assert.equal(stored.build.character.level, 325);
assert.deepEqual(JSON.parse(JSON.stringify(stored.build.myRoomFood)), expectedFood);
assert.equal(stored.build.guildFoodBuff, false);
assert.deepEqual(JSON.parse(JSON.stringify(stored.scenario.optimizationPreferences)), scenario.optimizationPreferences, '거리·요구조건·금지 크리스타 설정을 빌드 문서에 저장해야 합니다.');
assert.ok(!files.get('R6--빌드.json').includes('"storage"'), 'legacy storage 래퍼를 쓰면 안 됩니다.');
build = { ...build, character:{ ...build.character, level:1 } };
await repository.overwrite('R6--빌드.json');
assert.equal(repository.parseSavedBuild(files.get('R6--빌드.json')).build.character.level, 1);
build = { ...build, character:{ ...build.character, level:999 } };
await repository.load('R6--빌드.json');
assert.equal(restored.build.character.level, 1);
assert.deepEqual(JSON.parse(JSON.stringify(restored.build.myRoomFood)), expectedFood);
assert.equal(restored.build.guildFoodBuff, false);
assert.deepEqual(JSON.parse(JSON.stringify(restored.scenario.optimizationPreferences)), scenario.optimizationPreferences, '빌드 문서에서 최적화 사용자 설정을 복원해야 합니다.');
assert.equal(JSON.parse(local.get(repository.sessionStorageKey)).lastSession.build.character.level, 1);
assert.throws(() => repository.parseSavedBuild(JSON.stringify({ format:repository.format, schemaVersion:1, documentType:'saved-build', storage:{} })), /새 저장 계약/);
const legacyBuild = { ...build, activeBuffs:{ 'Knight:0':{ active:true, stacks:3 } }, externalOptions:[{ key:'ATK_P', value:10 }, { key:'DAMAGE_P', value:-45 }] };
const legacyDocument = { format:repository.format, schemaVersion:1, documentType:'saved-build', name:'legacy', createdAt:'2026-09-01T00:00:00.000Z', updatedAt:'2026-09-01T00:00:00.000Z', build:legacyBuild, scenario };
const recoveredDocument = repository.parseSavedBuild(JSON.stringify(legacyDocument));
assert.equal(recoveredDocument.schemaVersion, 2, '새 저장은 v2 계약을 사용해야 합니다.');
assert.deepEqual(JSON.parse(JSON.stringify(recoveredDocument.build.activeBuffs)), JSON.parse(JSON.stringify(legacyBuild.activeBuffs)), '버프 on/off와 스택은 legacy 저장에서도 보존해야 합니다.');
assert.deepEqual(JSON.parse(JSON.stringify(recoveredDocument.build.externalOptions)), [], 'v1 버프 프록시 옵션은 파일 불러오기에서 복원하면 안 됩니다.');
local.delete(repository.sessionStorageKey);
local.set('toram.auto-build.application-state.v1', JSON.stringify({ format:repository.format, schemaVersion:1, documentType:'application-state', appSettings:{}, lastSession:{ build:legacyBuild, scenario }, updatedAt:'2026-09-01T00:00:00.000Z' }));
repository.restoreLastSession();
assert.deepEqual(JSON.parse(JSON.stringify(restored.build.activeBuffs)), JSON.parse(JSON.stringify(legacyBuild.activeBuffs)), '마지막 세션도 버프 상태를 복원해야 합니다.');
assert.deepEqual(JSON.parse(JSON.stringify(restored.build.externalOptions)), [], '마지막 세션은 구형 버프 파생 옵션을 복원하면 안 됩니다.');
await repository.remove('R6--빌드.json');
assert.equal(files.size, 0);
assert.equal(repository.getUpdateSettings().checkOnStartup, true);
repository.setUpdateSettings({ checkOnStartup:false });
repository.saveLastSession();
assert.equal(repository.getUpdateSettings().checkOnStartup, false);
window.ToramBuildDraftStore.syncFromUi = () => { build.character.level = 326; };
repository.flushApplicationState();
const flushed = JSON.parse(local.get(repository.sessionStorageKey));
assert.equal(flushed.lastSession.build.character.level, 326);
assert.equal(flushed.appSettings.update.checkOnStartup, false);
assert.equal(flushed.schemaVersion, 2);
assert.equal(flushed.lastSession.update, undefined);
const realSet = window.localStorage.setItem;
window.localStorage.setItem = () => { throw new Error('quota'); };
assert.throws(() => repository.flushApplicationState(), /quota/);
window.localStorage.setItem = realSet;
console.log('R6 settings repository contract: PASS (including update preferences and strict pre-install flush)');
