import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

export async function publishRegistlets(check = false) {
  const root = resolve(import.meta.dirname,'../..');
  const bytes = await readFile(resolve(root,'data/sources/toram-registlet/catalog.json'));
  const source = JSON.parse(bytes), hash = createHash('sha256').update(bytes).digest('hex');
  const presentation = JSON.parse(await readFile(resolve(root,'data/sources/toram-registlet/presentation.json')));
  const reviewedRules = JSON.parse(await readFile(resolve(root,'data/sources/toram-registlet/reviewed-rules.json')));
  for (const ref of [reviewedRules.enhancement,...Object.values(reviewedRules.effects)].flatMap(rule => rule.sources)) {
    if (createHash('sha256').update(await readFile(resolve(root,ref.file))).digest('hex') !== ref.sha256) throw new Error('레지스트렛 추가 근거 해시가 다릅니다: ' + ref.file);
  }
  const version = createHash('sha256').update(JSON.stringify({sourceSha256:hash,presentation,reviewedRules})).digest('hex').slice(0,8);
  const categories = new Map();
  for (const [category,{ids}] of Object.entries(presentation.categories)) for (const id of ids) {
    if (categories.has(id)) throw new Error('레지스트렛 분류 ID가 중복됩니다: ' + id);
    categories.set(id,category);
  }
  if (categories.size !== source.registlets.length || source.registlets.some(row => !categories.has(row.registletId))) throw new Error('레지스트렛 분류가 원본 ID 전체와 일치하지 않습니다.');
  if (source.registlets.length !== 166 || source.acquisition.capturedStageCount !== 16) throw new Error('레지스트렛 추출 자료를 확인하세요.');
  const stages = new Map(source.acquisition.stages.map(stage => [stage.level,stage]));
  const items = source.registlets.map(row => ({id:row.registletId,names:row.names,descriptionTemplates:row.descriptionTemplates,
    levelCap:row.levelCap,enhancePowder:row.enhancePowder,baseValue:row.baseValue,category:categories.get(row.registletId),
    locations:row.acquisition.locations.map(place => ({level:place.level,names:stages.get(place.level).names,ranks:place.ranks}))}));
  const catalog = {schema:'toram.registlet-catalog.v1',cacheVersion:version,sourceSha256:hash,items,
    slotExpansion:{slotLimit:source.slotExpansion.slotLimit,costs:source.slotExpansion.costsByCurrentSlot}};
  const files = new Map([
    ['web/public/game-data/registlets/catalog.json',JSON.stringify(catalog) + '\n'],
    ['web/src/data/registlet-levels.mjs','// Generated by tools/extraction/publish-toram-registlets.mjs.\nexport const REGISTLET_LEVEL_CAPS = Object.freeze(' + JSON.stringify(Object.fromEntries(items.map(item => [item.id,item.levelCap]))) + ');\n']
  ]);
  for (const [path,text] of files) {
    const destination = resolve(root,path);
    if (check) {if (await readFile(destination,'utf8') !== text) throw new Error('Registlet publication differs: ' + path);}
    else {await mkdir(resolve(destination,'..'),{recursive:true}); await writeFile(destination,text);}
  }
  console.log(`Registlet publication: PASS (${items.length} definitions, six locales, 16 stages, ${check ? 'check' : 'written'})`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await publishRegistlets(process.argv.includes('--check'));
