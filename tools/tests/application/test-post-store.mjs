import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { randomUUID } from 'node:crypto';
import { createInventoryStore } from '../../../server/inventory-store.mjs';
import { createPostStore } from '../../../server/post-store.mjs';

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON; CREATE TABLE users(id TEXT PRIMARY KEY,nickname TEXT NOT NULL); INSERT INTO users VALUES (\'author\',\'작성자\'),(\'reader\',\'독자\');');
const inventory = createInventoryStore(db), posts = createPostStore(db,inventory);
const data = {character:{level:325,attributes:{STR:1,INT:1,VIT:1,AGI:1,DEX:1,CRT:0}}};
const source = inventory.create('author',{type:'status',schemaVersion:1,name:'내 스테이터스',data});
const build = inventory.create('author',{type:'build',schemaVersion:1,name:'부분 빌드',data:{status:{type:'status',schemaVersion:1,name:'비공개 하위 구성',data,provenance:[{kind:'inventory',objectId:source.id,revision:1}]}}});
const input = (record = source) => ({title:'공유 스테이터스 <img>',description:'검색 가능한 소개',tags:['입문','입문'],source:{objectId:record.id,revision:record.revision},scope:'whole',release:{name:'첫 버전',changeNotes:'처음 공개',gameVersion:''}});
const denied = (work,code) => assert.throws(work,error => error.apiCode === code,code);
try {
  const key = randomUUID(), first = posts.publish('author',input(),key);
  assert.equal(first.revision,1); assert.equal(first.latestRelease.number,1); assert.deepEqual(first.tags,['입문']);
  assert.equal(posts.list(null,new URLSearchParams()).total,1);
  assert.equal(posts.list(null,new URLSearchParams({q:'검색 가능한'})).total,1);
  assert.equal(posts.list(null,new URLSearchParams({tag:'입문'})).total,1);
  assert.equal(posts.list(null,new URLSearchParams({type:'build'})).total,0);
  assert.deepEqual(posts.publish('author',input(),key),first);
  denied(() => posts.publish('author',{...input(),title:'다른 요청'},key),'REQUEST_KEY_CONFLICT');
  denied(() => posts.publish('reader',input(),randomUUID()),'OBJECT_UNAVAILABLE');
  denied(() => posts.publish('author',input(),undefined),'REQUEST_KEY_REQUIRED');
  const noSnapshots = posts.list(null,new URLSearchParams()).items[0];
  assert.equal(noSnapshots.latestRelease.snapshot,undefined);
  assert.equal(noSnapshots.author.id,undefined);
  posts.favorite('reader',first.id,true); posts.favorite('reader',first.id,true);
  assert.equal(posts.list('reader',new URLSearchParams({favorites:'1'})).total,1);
  assert.equal(posts.list('author',new URLSearchParams({favorites:'1'})).total,0);
  denied(() => posts.list(null,new URLSearchParams({favorites:'1'})),'AUTH_REQUIRED');
  assert.equal(posts.get(first.id).favoriteCount,1);
  assert.equal(posts.get(first.id,'reader').favorited,true);
  const copied = posts.copy('reader',{postId:first.id,releaseNumber:1},randomUUID());
  assert.deepEqual(copied.provenance,[{kind:'release',postId:first.id,releaseNumber:1}]);
  const changed = inventory.update('author',source.id,{type:'status',schemaVersion:1,name:source.name,revision:1,data:{character:{...data.character,level:300}}});
  assert.equal(posts.get(first.id).release.snapshot.data.character.level,325);
  assert.equal(inventory.get('reader',copied.id).data.character.level,325);
  denied(() => posts.publish('author',{...input(),postRevision:1},randomUUID(),first.id),'REVISION_CONFLICT');
  const releaseInput = {source:{objectId:changed.id,revision:2},postRevision:1,release:{name:'새 버전',changeNotes:'레벨 변경',gameVersion:'사용자 표기'}};
  const second = posts.publish('author',releaseInput,randomUUID(),first.id);
  assert.equal(second.latestRelease.number,2); assert.equal(second.favoriteCount,1);
  assert.equal(posts.get(first.id,null,1).release.snapshot.data.character.level,325);
  assert.equal(posts.get(first.id).release.snapshot.data.character.level,300);
  assert.deepEqual(posts.history(first.id,null,new URLSearchParams()).items.map(item => item.number),[2,1]);
  denied(() => posts.manage('reader',first.id,{revision:2,visibility:'private'}),'SOURCE_UNAVAILABLE');
  denied(() => posts.manage('author',first.id,{revision:1,visibility:'private'}),'REVISION_CONFLICT');
  const copyKey = randomUUID(), newestCopy = posts.copy('reader',{postId:first.id,releaseNumber:2},copyKey);
  const privatePost = posts.manage('author',first.id,{revision:2,visibility:'private'});
  assert.equal(posts.list(null,new URLSearchParams()).total,0);
  denied(() => posts.get(first.id,'reader'),'SOURCE_UNAVAILABLE');
  denied(() => posts.copy('reader',{postId:first.id,releaseNumber:2},randomUUID()),'SOURCE_UNAVAILABLE');
  assert.equal(posts.copy('reader',{postId:first.id,releaseNumber:2},copyKey).id,newestCopy.id);
  assert.equal(inventory.get('reader',copied.id).data.character.level,325);
  const reopened = posts.manage('author',first.id,{revision:privatePost.revision,visibility:'public'});
  assert.equal(reopened.favoriteCount,1);
  posts.favorite('reader',first.id,false); posts.favorite('reader',first.id,false);
  assert.equal(posts.get(first.id).favoriteCount,0);
  const publishedBuild = posts.publish('author',input(build),randomUUID());
  assert.ok(!JSON.stringify(publishedBuild.release.snapshot).includes(source.id),'Private child IDs must be stripped');
  assert.ok(!JSON.stringify(publishedBuild.release.snapshot).includes(build.id),'Private source IDs must be stripped');
  const partial = posts.publish('author',{...input(build),scope:'status'},randomUUID());
  assert.equal(partial.type,'status'); assert.equal(partial.release.snapshot.data.character.level,325);
  denied(() => posts.publish('author',{...input(source),scope:'equipment'},randomUUID()),'REVISION_CONFLICT');
  denied(() => posts.publish('author',{...input(build),scope:'equipment'},randomUUID()),'INVALID_SCOPE');
  const copyBuild = posts.copy('reader',{postId:publishedBuild.id,releaseNumber:1},randomUUID());
  inventory.remove('author',build.id,{revision:1});
  assert.equal(posts.get(publishedBuild.id).type,'build'); assert.equal(inventory.get('reader',copyBuild.id).type,'build');
  const removed = posts.manage('author',first.id,{revision:reopened.revision,visibility:'deleted'});
  assert.equal(removed.visibility,'deleted'); denied(() => posts.get(first.id),'SOURCE_UNAVAILABLE');
  assert.equal(posts.list('author',new URLSearchParams(),true).total,3);
  denied(() => posts.manage('author',first.id,{revision:removed.revision,visibility:'public'}),'SOURCE_UNAVAILABLE');
  denied(() => posts.list(null,new URLSearchParams({sort:'rating'})),'INVALID_QUERY');
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
  console.log('Post store: PASS (partial/all snapshots, privacy, immutable releases, independent copies, owner/revision gates, request retries, favorites, search/history/visibility, source deletion)');
} finally { db.close(); }
