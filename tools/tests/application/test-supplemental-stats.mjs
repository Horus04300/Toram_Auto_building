import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const supplemental=require('../../../web/src/calculation/supplemental-stats.js');
function calculation(overrides={}) {
  const {ctx,...rest}=overrides;
  return {finalVIT:50,finalINT:80,finalDEX:70,finalAGI:40,finalMaxHP:1000,finalMaxMP:3200,
    ...rest,ctx:{level:100,armorType:'일반옷',preservedStats:{DEF:5,DEFP:10,MDEF:7,MDEFP:-20,ACC:3,ACCP:10,FLEE:4,FLEEP:20,HP_REGEN:3,HP_REGENP:20,MP_REGEN:2,MP_REGENP:50,REVIVE_TIME:20},...ctx}};
}
const regular=supplemental.evaluate(calculation(),{equipmentDefense:20});
assert.equal(regular.values.defense,192);
assert.equal(regular.values.magicDefense,167);
assert.equal(regular.values.accuracy,190);
assert.equal(regular.values.flee,172);
assert.equal(regular.values.hpRecovery,63);
assert.equal(regular.values.mpRecovery,33);
assert.equal(regular.values.reviveSeconds,280);
for(const [armorType,defense,magicDefense,flee] of [['경량옷',128,103,274],['중량옷',269,247,82],['없음',76,61,370]]) {
  const result=supplemental.evaluate(calculation({ctx:{armorType}}),{equipmentDefense:20});
  assert.equal(result.values.defense,defense,armorType);
  assert.equal(result.values.magicDefense,magicDefense,armorType);
  assert.equal(result.values.flee,flee,armorType);
}
const missing=supplemental.evaluate(calculation());
assert.equal(missing.values.defense,null);
assert.equal(missing.values.magicDefense,null);
assert.deepEqual(missing.requirements.find(input=>input.key==='equipmentDefense'),{key:'equipmentDefense',label:'장비 DEF 합계',unit:'DEF'});
const cap=supplemental.evaluate(calculation({finalMaxHP:100000,finalMaxMP:99999,ctx:{preservedStats:{}}}),{equipmentDefense:0});
assert.equal(cap.values.hpRecovery,4009);
assert.equal(cap.values.mpRecovery,21);
const negative=supplemental.evaluate(calculation({ctx:{preservedStats:{DEFP:-200,MDEFP:-200,HP_REGENP:-150,HP_REGEN:-3,MP_REGENP:-150,MP_REGEN:-2,REVIVE_TIME:-20}}}),{equipmentDefense:20});
assert.equal(negative.values.defense,-170);
assert.equal(negative.values.magicDefense,-200);
assert.equal(negative.values.hpRecovery,-28);
assert.equal(negative.values.mpRecovery,-12);
assert.equal(negative.values.reviveSeconds,320);
assert.equal(supplemental.evaluate(calculation(),{equipmentDefense:0,avatarRevivePercent:50}).values.reviveSeconds,130);
const original=calculation({ctx:{preservedStatContributions:{ACCP:[7,13,-2],FLEEP:[7,13,-2],HP_REGENP:[7,13,-2]}}});
const snapshot=JSON.stringify(original);
const fromSources=supplemental.evaluate(original,{equipmentDefense:0});
const f=Math.fround;
const nativeRate=[7,13,-2].reduce((rate,value)=>f(rate+f(f(value)*f(.01))),1);
assert.equal(fromSources.values.accuracy,Math.trunc(f(170*nativeRate))+3);
assert.equal(fromSources.values.flee,Math.trunc(f(140*nativeRate))+4);
assert.equal(JSON.stringify(original),snapshot,'Supplemental evaluation must not mutate calculation/options');
const actions=supplemental.evaluate(calculation({ctx:{preservedStats:{ABS_ACC:25,ANTICIPATE:30,GUARD_BREAK:40,ITEM_DELAY:Math.fround(100*Math.fround(.01))}}}),{equipmentDefense:0,baseHitChance:60,targetAvoidChance:50,targetGuardChance:50,baseItemCooldownSeconds:10});
assert.equal(actions.outcomes.hitChance,70);
assert.equal(actions.outcomes.targetAvoidChance,35);
assert.equal(actions.outcomes.targetGuardChance,30);
assert.equal(actions.outcomes.itemCooldownSeconds,9);
assert.equal(supplemental.evaluate(calculation({ctx:{preservedStats:{ITEM_DELAY:100}}}),{baseItemCooldownSeconds:10}).values.itemCooldownSeconds,5);
assert.equal(supplemental.evaluate(calculation({ctx:{preservedStats:{ITEM_DELAY:-1}}}),{baseItemCooldownSeconds:10}).values.itemCooldownSeconds,11);
for(const [amount,expected] of [[-10,60],[0,60],[100,72],[200,72]])assert.equal(supplemental.evaluate(calculation({ctx:{preservedStats:{ABS_ACC:amount}}}),{baseHitChance:60}).outcomes.hitChance,expected);
assert.equal(supplemental.evaluate(calculation({ctx:{preservedStats:{ITEM_DELAY:100}}}),{baseItemCooldownSeconds:100}).values.itemCooldownSeconds,50,'Raw140 caps at500, so item reduction cannot exceed50%');
const ordered=supplemental.evaluate(calculation({ctx:{preservedStats:{ANTICIPATE:50,GUARD_BREAK:50},preservedStatContributions:{ANTICIPATE:[150,-100],GUARD_BREAK:[150,-100]}}}),{targetAvoidChance:50,targetGuardChance:50});
assert.equal(ordered.outcomes.targetAvoidChance,50,'Instant bonuses cap after each source contribution');
