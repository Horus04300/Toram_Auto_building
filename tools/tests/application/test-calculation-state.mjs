import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {loadSavedBuildEnvironment} from '../../support/saved-build-headless-environment.mjs';

const env=await loadSavedBuildEnvironment(),store=env.ToramBuildDraftStore,application=env.ToramApplication;
const registry=env.ToramSkillEffectRegistry,policies=env.ToramCalculationPolicies;
registry.register([{id:'Audit:0',kind:'buff'}]);
assert.throws(()=>registry.register([{id:'Audit:1'},{id:'Audit:0'}]),/중복/);
assert.equal(registry.get('Audit:1'),undefined,'Rejected registration cannot partly commit');
assert.equal(policies.matchesCrystaCondition({mainType:'한손검',subType:'방패'},{kind:'both-weapon-slots',main:'한손검',sub:'방패'}),true);
assert.equal(policies.matchesCrystaCondition({mainType:'한손검',subType:''},{kind:'either-weapon-slot',types:['활']}),false);
const stats={atkF:0};policies.applyStat(stats,'ATK',5);assert.equal(stats.atkF,5);
const saved=env.ToramSettingsRepository.parseSavedBuild(await readFile(new URL('../../../samples/마법) 지팡이 크법 세팅 - pelio s.json',import.meta.url),'utf8'));
store.restoreSession(saved);
const revision=store.revision(),result=application.CalculateBuild();
assert.ok(Number.isFinite(result.calculation.damageFactor));
assert.deepEqual(result.snapshot.build,saved.build);
assert.deepEqual(result.snapshot.scenario,saved.scenario);
assert.equal(result.snapshot.baseContext.level,saved.build.character.level);
assert.ok(Object.isFrozen(result.snapshot.build));
store.commitBuild({character:{...saved.build.character,level:100}});
assert.equal(store.revision(),revision+1);
assert.equal(result.snapshot.build.character.level,saved.build.character.level,'Snapshots survive subsequent edits');
assert.equal(application.CreateCalculationSnapshot().baseContext.level,100);
store.commitBuild({character:{...saved.build.character,level:100}});
assert.equal(store.revision(),revision+1,'Equivalent commits preserve running work');
assert.throws(()=>{store.getBuild().character.level=1;},TypeError);
assert.throws(()=>application.CreateCalculationSnapshot({build:{},scenario:{}}));
assert.equal(store.getBuild().character.level,100,'Malformed explicit calculation input cannot alter the Store');
console.log('Calculation state: PASS (headless real calculation, policy, atomic registry, immutable Store/snapshot, semantic revision, rejected input)');
