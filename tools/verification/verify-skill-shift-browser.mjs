import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomBytes,createHash } from 'node:crypto';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createAccountServer } from '../../server/account-server.mjs';

if (!process.env.CODEX_PLAYWRIGHT_PATH) throw new Error('Set CODEX_PLAYWRIGHT_PATH to the installed playwright module.');
const {chromium} = createRequire(import.meta.url)(process.env.CODEX_PLAYWRIGHT_PATH);
const directory = await mkdtemp(join(tmpdir(),'toram-skill-shift-')), database = join(directory,'accounts.sqlite'), origin = 'http://127.0.0.1:18789';
const server = createAccountServer({publicOrigin:origin,database}), token = randomBytes(32).toString('base64url'), db = new DatabaseSync(database);
db.prepare('INSERT INTO users VALUES (?,?,?)').run('shift-user','shift-google','스킬 조작 테스터');
db.prepare('INSERT INTO sessions VALUES (?,?,?,?)').run(createHash('sha256').update(token).digest('hex'),'shift-user','web',Date.now() + 600000); db.close();
let browser;
try {
  await new Promise((done,reject) => {server.once('error',reject); server.listen(18789,'127.0.0.1',done);});
  browser = await chromium.launch({channel:'chrome',headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}}), page = await context.newPage(), errors = [];
  page.on('pageerror',error => errors.push(error.message));
  page.on('console',event => {if (['error','warning'].includes(event.type())) errors.push(event.text());});
  await context.addCookies([{name:'toram_session',value:token,url:origin,httpOnly:true,sameSite:'Lax'}]);
  await page.goto(origin + '/inventory?type=skill_tree&skillCategory=Weapon_Skills&treeId=Blade');
  const inventory = page.locator('#inventoryWorkspace'), panel = inventory.locator('.inventory-skill-editor');
  const wait = async () => {await panel.waitFor({state:'visible'}); await page.waitForFunction(() => !document.querySelector('#inventoryWorkspace').hasAttribute('aria-busy'));};
  await wait(); assert.match(await page.title(),/인벤토리/);
  const tree = await page.evaluate(() => window.SKILL_TREE_DATA.trees.find(tree => tree.id === 'Blade'));
  const paths = tree.skills.map(skill => {const path = []; for (let current = skill; current; current = tree.skills.find(candidate => candidate.id === current.prereq)) path.push(current.id); return path;});
  const path = paths.reduce((best,current) => current.length > best.length ? current : best), targetIndex = tree.skills.findIndex(skill => skill.id === path[0]);
  const nodes = panel.locator('.skill-node');
  assert.equal(await panel.getByRole('button',{name:'10',exact:true}).getAttribute('aria-pressed'),'true','Inventory defaults to 10 points');
  await nodes.nth(targetIndex).click();
  for (const id of path.slice(1)) assert.match(await nodes.nth(tree.skills.findIndex(skill => skill.id === id)).getAttribute('title'),/Lv 5\/10/);
  await panel.getByRole('button',{name:'1',exact:true}).click(); await nodes.nth(targetIndex).click({modifiers:['Shift']});
  for (const [index,skill] of tree.skills.entries()) assert.match(await nodes.nth(index).getAttribute('title'),new RegExp(`Lv ${path.includes(skill.id) ? 10 : 0}/10`));
  const save = inventory.locator('[data-action="save"]'); await save.click(); await wait();
  const id = new URL(page.url()).searchParams.get('selected'); assert.ok(id);
  const stored = async () => {const response = await context.request.get(origin + '/api/inventory/' + id); assert.ok(response.ok()); return response.json();};
  const saved = await stored(); for (const id of path) assert.equal(saved.data.levels[id],10);
  await nodes.nth(targetIndex).click({modifiers:['Shift']}); await save.click(); await wait(); assert.equal((await stored()).revision,saved.revision,'Repeated Shift must not create a revision');
  await page.reload(); await wait();
  assert.equal(await panel.getByRole('button',{name:'10',exact:true}).getAttribute('aria-pressed'),'true','Opening the editor restores the 10-point default');
  for (const id of path) assert.match(await nodes.nth(tree.skills.findIndex(skill => skill.id === id)).getAttribute('title'),/Lv 10\/10/);
  const screenshot = join(directory,'shift-path.png'); await page.screenshot({path:screenshot});
  await nodes.nth(targetIndex).click({button:'right'}); assert.match(await nodes.nth(targetIndex).getAttribute('title'),/Lv 0\/10/);
  await page.goto(origin + '/calculator'); await page.waitForFunction(() => Boolean(window.ToramSkillUi));
  await page.locator('#appTabButton-skills').click();
  assert.equal(await page.locator('#calculatorWorkspace .skill-point-step.active').innerText(),'10','Calculator defaults to 10 points');
  const before = await page.evaluate(() => window.ToramSkillUi.getInvestments());
  await page.locator('#combatSkillStage .skill-node').nth(targetIndex).click({modifiers:['Shift']});
  const after = await page.evaluate(() => window.ToramSkillUi.getInvestments());
  for (const skill of tree.skills) assert.equal(after.Blade[skill.id],path.includes(skill.id) ? 10 : before.Blade[skill.id]);
  for (const treeId of Object.keys(before).filter(id => id !== 'Blade')) assert.deepEqual(after[treeId],before[treeId]);
  assert.deepEqual(errors,[]);
  console.log('Skill Shift browser: PASS (build/web, Chrome, calculator/inventory, capped target + full prerequisite path, point step ignored, branches preserved, save/reload/no-op, right-click)');
  console.log('Screenshot: ' + screenshot);
} finally {await browser?.close(); await new Promise(done => server.close(done)); for (const suffix of ['', '-wal', '-shm']) await rm(database + suffix,{force:true});}
