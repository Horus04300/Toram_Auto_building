import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomBytes,createHash} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {createAccountServer} from '../../server/account-server.mjs';
import {createWebDevServer} from '../web-dev.mjs';

// Browser plugin is unavailable; use the existing Playwright/Chrome verification path.
const {chromium} = createRequire(import.meta.url)(process.env.CODEX_PLAYWRIGHT_PATH);
const directory = await mkdtemp(join(tmpdir(),'toram-registlet-ui-'));
const database = join(directory,'accounts.sqlite'), origin = 'http://127.0.0.1:18791';
const source = process.argv.includes('--source');
const server = (source ? createWebDevServer : createAccountServer)({publicOrigin:origin,database});
const db = new DatabaseSync(database), token = randomBytes(32).toString('base64url');
db.prepare('INSERT INTO users VALUES (?,?,?)').run('registlet-user','fixture-google-sub','레지스트렛 테스터');
db.prepare('INSERT INTO sessions VALUES (?,?,?,?)').run(createHash('sha256').update(token).digest('hex'),'registlet-user','web',Date.now() + 600000);
db.close();
let browser;
const errors = [], screenshots = [], writes = [], requests = [];
try {
  await new Promise((done,reject) => {server.once('error',reject); server.listen(18791,'127.0.0.1',done);});
  browser = await chromium.launch({channel:'chrome',headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}}), page = await context.newPage();
  page.on('pageerror',error => errors.push(error.message));
  page.on('console',event => {if (['error','warning'].includes(event.type())) errors.push(event.text());});
  page.on('request',request => {requests.push(request.url()); if (request.method() !== 'GET') writes.push(request.url());});
  page.on('dialog',dialog => dialog.accept());
  const catalog = page.locator('#catalogWorkspace'), inventory = page.locator('#inventoryWorkspace');
  const action = (workspace,name) => workspace.locator(`[data-action="${name}"]`);
  async function ready(workspace) {await workspace.waitFor({state:'visible'}); await page.waitForFunction(id => !document.getElementById(id).hasAttribute('aria-busy'),await workspace.getAttribute('id'));}
  async function capture(name) {const path = join(directory,name + '.png'); await page.screenshot({path}); screenshots.push(path);}
  async function saved(id) {const response = await context.request.get(origin + '/api/inventory/' + id); assert.ok(response.ok()); return response.json();}
  await page.goto(origin); await page.locator('#homeWorkspace').waitFor({state:'visible'});
  assert.equal(requests.some(url => url.includes('/game-data/registlets/')),false);
  await page.goto(origin + '/catalog?section=registlets'); await ready(catalog);
  assert.match(await page.title(),/도감/); assert.match(await catalog.locator('.catalog-count').innerText(),/166개/);
  const search = catalog.locator('.catalog-search');
  const kinds = catalog.locator('.catalog-kind-rail');
  for (const [kind,count] of [['stats',10],['status',16],['support',32],['skills',108],['all',166]]) {
    await kinds.locator(`[data-registlet-kind="${kind}"]`).click(); await ready(catalog);
    assert.match(await catalog.locator('.catalog-count').innerText(),new RegExp(count + '개'));
  }
  const majorBox = await catalog.locator('.catalog-major-rail').boundingBox(), kindBox = await kinds.boundingBox();
  assert.ok(kindBox.x >= majorBox.x + majorBox.width,'Registlet categories use the same second rail as items and bosses');
  await search.locator('[name="q"]').fill('맹독 회복'); await search.getByRole('button',{name:'검색',exact:true}).click(); await ready(catalog);
  await catalog.locator('[data-entry-id="12"]').click(); await ready(catalog);
  const level = catalog.locator('[name="registletLevel"]');
  assert.equal(await level.getAttribute('max'),'30');
  assert.equal(await catalog.getByRole('button',{name:'효과 보기',exact:true}).count(),0);
  await level.fill('2'); assert.match(await catalog.locator('.catalog-description').innerText(),/2%/);
  assert.match(await catalog.locator('.registlet-formulas').innerText(),/2 × 1/);
  assert.match(await catalog.locator('.registlet-enhancement').innerText(),/5개/);
  await catalog.locator('[name="registletMaterialLevel"]').fill('10');
  assert.match(await catalog.locator('.registlet-enhancement').innerText(),/Lv2 → Lv12/);
  await level.fill('29'); assert.match(await catalog.locator('.registlet-enhancement').innerText(),/Lv29 → Lv30/);
  await catalog.locator('[name="registletMaterialLevel"]').fill('1');
  await level.fill('30');
  assert.match(await catalog.locator('.catalog-description').innerText(),/30%/);
  assert.match(await catalog.locator('.catalog-acquisition').innerText(),/Lv270.*A\/S/);
  assert.equal(await catalog.locator('.catalog-slot-expansion').count(),0,'Slot costs must not be repeated in gem details');
  await capture('catalog-desktop');
  const beforeGuest = writes.length;
  await action(catalog,'save-registlet').click(); await catalog.locator('.catalog-status').filter({hasText:'로그인 후'}).waitFor();
  assert.equal(writes.length,beforeGuest,'Guests must not write inventory');
  await context.addCookies([{name:'toram_session',value:token,url:origin,httpOnly:true,sameSite:'Lax'}]);
  await page.reload(); await ready(catalog);
  await action(catalog,'save-registlet').click(); await action(catalog,'inventory').waitFor({state:'visible'});
  await action(catalog,'inventory').click(); await ready(inventory);
  assert.equal(new URL(page.url()).searchParams.get('type'),'registlet');
  const id = new URL(page.url()).searchParams.get('selected'), editor = inventory.locator('.inventory-registlet-editor');
  assert.equal(await editor.locator('[name="registletLevel"]').inputValue(),'30');
  assert.ok(await action(inventory,'apply').isHidden()); assert.ok(await action(inventory,'merge').isHidden());
  assert.ok(await inventory.locator('.inventory-capture-toggle').isHidden());
  await editor.locator('[name="registletLevel"]').fill('15'); assert.match(await editor.locator('.registlet-formulas').innerText(),/15 × 1/); await action(inventory,'save').click(); await ready(inventory);
  assert.equal((await saved(id)).data.selection.level,15);
  await page.reload(); await ready(inventory);
  assert.equal(await editor.locator('[name="registletLevel"]').inputValue(),'15');
  await editor.locator('[name="registletLevel"]').fill('31'); await action(inventory,'save').click(); await ready(inventory);
  assert.match(await inventory.locator('.inventory-status').innerText(),/1~30/);
  assert.equal((await saved(id)).data.selection.level,15);
  await editor.locator('[name="registletLevel"]').fill('14'); await editor.getByRole('button',{name:'도감에서 보기'}).click(); await ready(catalog);
  assert.equal((await saved(id)).data.selection.level,14,'Leaving inventory saves a valid edit');
  assert.equal(new URL(page.url()).searchParams.get('level'),'14');
  await page.goBack(); await ready(inventory); await capture('inventory-desktop');
  await page.setViewportSize({width:390,height:844});
  await action(inventory,'list').click(); await ready(inventory);
  await action(inventory,'create').click(); await ready(inventory);
  await editor.locator('[name="registletId"]').selectOption('1036');
  assert.equal(await editor.locator('[name="registletLevel"]').getAttribute('max'),'1');
  assert.match(await editor.locator('.registlet-effect').innerText(),/이지스/);
  await action(inventory,'list').click(); await ready(inventory);
  await action(inventory,'save').click(); await ready(inventory);
  const secondId = new URL(page.url()).searchParams.get('selected');
  assert.notEqual(secondId,id); assert.equal((await saved(secondId)).data.selection.registletId,1036);
  await inventory.locator(`[data-entry-id="${secondId}"]`).click(); await ready(inventory);
  await capture('inventory-mobile');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await action(inventory,'remove').click(); await ready(inventory);
  assert.equal((await context.request.get(origin + '/api/inventory?type=registlet')).ok(),true);
  await page.goto(origin + '/catalog?section=registlets&selected=50'); await ready(catalog);
  assert.match(await catalog.locator('.catalog-summary').innerText(),/최대 Lv1/);
  await catalog.locator('.catalog-navigation-toggle').click();
  assert.ok(await catalog.locator('[data-section="registlets"]').isVisible());
  await catalog.locator('[data-section="registlets"]').click(); await ready(catalog);
  await kinds.locator('[data-registlet-kind="all"]').click(); await ready(catalog);
  await catalog.locator('[data-entry-id]').first().click(); await ready(catalog);
  await capture('catalog-mobile');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await catalog.locator('.catalog-navigation-toggle').click();
  await kinds.locator('[data-registlet-kind="slots"]').click(); await ready(catalog);
  assert.ok(await catalog.locator('.catalog-slot-page').isVisible()); assert.ok(await search.isHidden());
  assert.equal(await catalog.locator('.catalog-slot-page tbody tr').count(),9);
  assert.match(await catalog.locator('.catalog-slot-page').innerText(),/500,000/);
  assert.match(await catalog.locator('.catalog-slot-page').innerText(),/9,739,500/);
  await capture('slot-expansion-mobile');
  await page.setViewportSize({width:1280,height:900}); await capture('slot-expansion-desktop');
  await page.goto(origin + '/catalog?section=registlets&registletKind=skills&selected=207&level=4'); await ready(catalog);
  await catalog.locator('[name="registletSkillLevel"]').fill('6');
  assert.match(await catalog.locator('.catalog-description').innerText(),/5%/);
  assert.match(await catalog.locator('.registlet-formulas').innerText(),/6 \+ 4/);
  await page.goto(origin + '/catalog?section=registlets&registletKind=skills&selected=1053'); await ready(catalog);
  await level.fill('4');
  assert.match(await catalog.locator('.registlet-formulas').innerText(),/스택 상한/);
  assert.match(await catalog.locator('.registlet-formulas tbody tr').first().locator('td').last().innerText(),/4/);
  await capture('skull-shaker-desktop');
  await page.setViewportSize({width:390,height:844}); await capture('skull-shaker-mobile');
  assert.equal(await page.locator(':modal').count(),0);
  assert.equal(await page.evaluate(() => Boolean(window.ToramApp.calculatorReady)),false);
  assert.deepEqual(errors,[]);
  console.log(`Registlet browser: PASS (${source ? 'source' : 'built web'}, Chrome 1280/390px, lazy catalog, four categories/second rail, live formulas/results, hidden Skull Shaker stacks, material costs, separate slots, guest guard, save/edit/reload/leave/delete, independent calculator, no console errors)`);
  console.log('Screenshots: ' + screenshots.join(' | '));
} finally {
  await browser?.close(); await new Promise(done => server.close(done));
  for (const suffix of ['','-wal','-shm']) await rm(database + suffix,{force:true});
}
